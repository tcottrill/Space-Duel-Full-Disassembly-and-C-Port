"""What each Space Duel RAM variable is for.

The alias table in spaceduel_defines.asm is recovered mechanically (see
rammap.py); this file supplies the prose.  Descriptions are Atari's own,
taken from the trailing comments on the .BLKB declarations in ASTRD2.MAC,
the equates in AS2DEC.MAC, the sound channel arrays in AS2POK.MAC and the
coin variables in COIN65.MAC, rewritten in sentence case and expanded with
the array lengths and bit encodings the source states elsewhere.

Two things the reader needs to know about the names themselves:

  * DEC MACRO-65 symbols are significant to 6 characters, so a few names
    arrive truncated (CMSBSE is CMSBSET, PL0ARE is PL0AREA).

  * An address is named after whichever symbol resolves to it, and Atari's
    sources define plenty of *constants* whose value happens to equal a low
    RAM address.  Where such a constant outranks the real variable, the
    entry opens with the cell's true identity - "VGLIST+1" and so on - and
    carries the COLLIDES marker, which lookup() returns as a flag.

Keys are alias names; ADDR is the address the name is expected to land on,
and emit_defines.py warns if the recovered map disagrees, so this file
cannot drift silently away from rammap.py.
"""

