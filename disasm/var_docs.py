def lookup(name, addr):
    """(description, collides) for an alias, or (None, False) if undocumented.
    Warns on stderr when the recovered address is not the one documented."""
    rec = DOCS.get(name)
    if rec is None:
        return None, False
    want, text = rec
    if want != addr:
        import sys
        sys.stderr.write("var_docs: %s documented at $%04X but recovered at $%04X\n"
                         % (name, want, addr))
    if text.startswith(COLLIDES):
        return text[len(COLLIDES):], True
    return text, False
